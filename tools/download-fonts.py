#!/usr/bin/env python3
"""Download Literata and Manrope from Google Fonts into assets/fonts/
and write assets/css/fonts.css that points to the local files.

Run once from the project folder:   py tools/download-fonts.py
(needs an internet connection; Python 3 standard library only)
"""
import pathlib, re, urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONTS = ROOT / "assets" / "fonts"
CSS_OUT = ROOT / "assets" / "css" / "fonts.css"
URL = ("https://fonts.googleapis.com/css2?family=Literata:opsz,wght@7..72,400..600"
       "&family=Manrope:wght@400..700&display=swap")
UA = ("Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
      "(KHTML, like Gecko) Chrome/124.0 Safari/537.36")
KEEP = {"latin", "latin-ext", "greek", "cyrillic"}  # EN/IT + Greek + Russian


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read()


def convert(css, fetch_fn, fonts_dir):
    blocks, by_url, used = [], {}, set()
    for m in re.finditer(r"/\*\s*([\w-]+)\s*\*/\s*(@font-face\s*\{.*?\})", css, re.S):
        subset, block = m.groups()
        if subset not in KEEP:
            continue
        family = re.search(r"font-family:\s*'([^']+)'", block).group(1)
        weight = re.search(r"font-weight:\s*([^;]+);", block).group(1).strip().replace(" ", "-")
        url = re.search(r"url\((https://[^)]+?\.woff2)\)", block).group(1)
        if url not in by_url:
            name = f"{family.lower()}-{subset}-{weight}.woff2"
            n = 2
            while name in used:
                name = f"{family.lower()}-{subset}-{weight}-{n}.woff2"
                n += 1
            used.add(name)
            (fonts_dir / name).write_bytes(fetch_fn(url))
            by_url[url] = name
            print("downloaded", name)
        blocks.append(block.replace(url, "../fonts/" + by_url[url]))
    return "/* Generated by tools/download-fonts.py */\n" + "\n".join(blocks) + "\n"


if __name__ == "__main__":
    FONTS.mkdir(parents=True, exist_ok=True)
    out = convert(fetch(URL).decode("utf-8"), fetch, FONTS)
    CSS_OUT.write_text(out, encoding="utf-8")
    print("wrote", CSS_OUT)
